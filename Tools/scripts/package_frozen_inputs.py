import argparse
import hashlib
import json
import shutil
from pathlib import Path


INPUTS = (
    "pm10_unique_locations_2024.rds",
    "era5_combined_2024.rds",
    "production_30000_online_grid_preparation.rds",
)


def sha256_file(path):
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def main():
    project = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(description="Package exact frozen inputs for manual release upload; do not upload or alter originals.")
    parser.add_argument("--source", type=Path, default=project / "Data")
    parser.add_argument("--output", type=Path, default=project / "Tools/results/frozen_inputs_release")
    parser.add_argument("--release-tag", default="v1.0.0")
    parser.add_argument("--dry-run", action="store_true")
    arguments = parser.parse_args()
    source = arguments.source.resolve()
    output = arguments.output.resolve()
    if source == output:
        parser.error("Output must differ from the input directory.")
    for name in INPUTS:
        if not (source / name).is_file():
            parser.error(f"Missing frozen input: {source / name}")
        if (source / name).stat().st_size >= 2 * 1024**3:
            parser.error(f"Release asset is not below 2 GiB: {name}")
    print(json.dumps({"files": {name: (source / name).stat().st_size for name in INPUTS},
                      "output": str(output), "release_tag": arguments.release_tag,
                      "dry_run": arguments.dry_run}, indent=2))
    if arguments.dry_run:
        return
    if output.exists():
        parser.error("Output already exists. Use a new directory; existing assets are not overwritten.")
    output.mkdir(parents=True)
    checksums = []
    for name in INPUTS:
        expected = sha256_file(source / name)
        shutil.copy2(source / name, output / name)
        if sha256_file(output / name) != expected:
            raise RuntimeError(f"Copy integrity check failed: {name}")
        checksums.append(f"{expected}  {name}")
    (output / "SHA256SUMS").write_text("\n".join(checksums) + "\n", encoding="utf-8")
    guide = f"""# Frozen manuscript analysis inputs ({arguments.release_tag})

These exact prepared inputs were used for the European PM10 analysis:
2,989 unique monitoring locations, 366 days in 2024, and 5,297 prediction sites.

- pm10_unique_locations_2024.rds: named R list with observations,
  station_information, analysis_dates, Y_observed, Y_imputed, imputed_mask,
  selection_audit and settings. Responses retain the original PM10 units.
- era5_combined_2024.rds: matched-source meteorological grid with Longitude,
  Latitude, Date, Temperature, Precipitation and Wind. Date is a zero-based
  day offset from 2024-01-01. Units are degrees Celsius, metres and m/s.
- production_30000_online_grid_preparation.rds: station/weather matching,
  dates, fixed scaling, geographical bounds and prediction grid; not posterior
  chains or predicted surfaces.

Place these three files under Data/ in the matching code checkout. Verify:

    python Tools/scripts/verify_frozen_inputs.py --input-dir Data --checksums PATH/TO/SHA256SUMS
    Rscript Tools/scripts/validate_preparation_inputs.R

Only launch model fitting separately after validation. Simulation data are
generated by the simulation scripts and require no real-data release assets.

Source attribution: PM10 and station metadata originate from the European
Environment Agency Air Quality download/AQ Viewer services; meteorological
variables originate from Copernicus Climate Data Store ERA5 daily statistics.
The prepared sample retains the authors' final station decisions, imputation,
weather matching, scaling and prediction support. See manuscript provenance.

This package supports reproduction FROM PREPARED INPUTS, not independent
regeneration of the original downloads. Original-download availability is not
asserted. SHA-256 checksums verify file integrity; they do not establish raw
preprocessing validity or model convergence. Files have not been regenerated
or reserialised by packaging.

Before public upload, the authors must confirm applicable data redistribution
terms and attribution, add any required source notices/access dates, and link
this release to the corresponding code tag. No new rights over third-party
data are granted by this README. Packaging does not commit, tag or upload.
"""
    (output / "INPUTS_README.md").write_text(guide, encoding="utf-8")
    print("Copied and verified all three inputs; README and SHA256SUMS prepared. No upload, commit or fitting performed.")


if __name__ == "__main__":
    main()
